let storedLang = 'zh'
try { storedLang = localStorage.getItem('lang') || 'zh' } catch (e) {}
if (storedLang !== 'zh' && storedLang !== 'en') storedLang = 'zh'

export const i18nState = reactive({ lang: storedLang })

export function t(key, vars) {
  const lang = i18nState.lang
  const table = I18N[lang] || I18N.zh
  let str = table[key]
  if (str === undefined) str = I18N.zh[key]
  if (str === undefined) str = key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.split('{' + k + '}').join(String(v ?? ''))
    }
  }
  return str
}

export function setLanguage(lang) {
  if (lang !== 'zh' && lang !== 'en') lang = 'zh'
  i18nState.lang = lang
  try { localStorage.setItem('lang', lang) } catch (e) {}
}
